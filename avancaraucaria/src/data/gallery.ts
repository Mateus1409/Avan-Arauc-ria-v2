export function getGalleryBySlug(slug: string): GalleryItem | undefined {
  return gallery.find((g) => g.slug === slug);
}

export function getAllGallerySlugs(): string[] {
  return gallery.map((g) => g.slug);
}

export function getLatestGallery(limit = 6): GalleryItem[] {
  return gallery
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
    .slice(0, limit);
}