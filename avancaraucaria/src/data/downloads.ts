export function getDownloadById(id: string): DownloadItem | undefined {
  return downloads.find((d) => d.id === id);
}

export function getDownloadsByCategory(categorySlug: string): DownloadItem[] {
  if (categorySlug === 'todos') return downloads;
  return downloads.filter((d) => d.categorySlug === categorySlug);
}

export function getDownloadsByYear(year: string): DownloadItem[] {
  return downloads.filter((d) => d.year === year);
}

export function getFeaturedDownloads(limit = 3): DownloadItem[] {
  return downloads.filter((d) => d.featured).slice(0, limit);
}

export function searchDownloads(query: string): DownloadItem[] {
  const lowerQuery = query.toLowerCase();
  return downloads.filter(
    (d) =>
      d.title.toLowerCase().includes(lowerQuery) ||
      d.description.toLowerCase().includes(lowerQuery) ||
      d.category.toLowerCase().includes(lowerQuery)
  );
}